import assert from 'node:assert/strict';
import { nachoRopa } from './ropa.mjs';
import { weekdayIso, nextYmd, ymdInZone, isFestivo, isLaborable } from './fechas.mjs';

assert.equal(weekdayIso('2026-09-21'), 1);
assert.equal(weekdayIso('2026-09-23'), 3);
assert.equal(weekdayIso('2026-09-24'), 4);
assert.equal(weekdayIso('2026-09-20'), 7);
assert.equal(nextYmd('2026-09-15'), '2026-09-16');
assert.equal(ymdInZone(new Date('2026-09-15T23:30:00+02:00')), '2026-09-15');
assert.equal(ymdInZone(new Date('2026-09-15T23:30:00Z')), '2026-09-16');
assert.equal(isFestivo('2026-10-12'), true);
assert.equal(isLaborable('2026-10-12'), false);
assert.equal(isFestivo('2026-10-13'), false);
assert.equal(isLaborable('2026-10-13'), true);
assert.equal(isFestivo('2026-12-25'), true);
assert.equal(isLaborable('2026-12-25'), false);
assert.equal(isFestivo('2027-03-29'), true);
assert.equal(isLaborable('2027-03-18'), true);

const ROPA = { ropa: { chandal_weekdays: [1, 2, 5], excepciones: { '2026-10-22': 'chandal' } } };
assert.equal(nachoRopa('2026-09-21', ROPA), 'chándal');
assert.equal(nachoRopa('2026-09-22', ROPA), 'chándal');
assert.equal(nachoRopa('2026-09-23', ROPA), 'uniforme');
assert.equal(nachoRopa('2026-09-24', ROPA), 'uniforme');
assert.equal(nachoRopa('2026-09-25', ROPA), 'chándal');
assert.equal(nachoRopa('2026-09-19', ROPA), '');
assert.equal(nachoRopa('2026-09-20', ROPA), '');
assert.equal(nachoRopa('2026-10-12', ROPA), '');
assert.equal(nachoRopa('2026-10-13', ROPA), 'chándal');
assert.equal(nachoRopa('2026-10-16', ROPA), 'chándal');
assert.equal(nachoRopa('2026-10-22', ROPA), 'chándal');
assert.equal(nachoRopa('2026-09-21'), '');
